package Atv_for_java;

public class Atv1 {
    public class Crescente {
    public static void main(String[] args) {
        for (int i = 10; i <= 20; i++) {
            System.out.println(i);
        }
    }
    
    public class Decrescente {
        public static void main(String[] args) {
            for (int i = 20; i >= 10; i--) {
                System.out.println(i);
            }
        } 
    }
    
    

public class ImparesPares {
    public static void main(String[] args) {
        for (int i = 1; i <= 51; i++) {
            if (i % 2 != 0) {
                System.out.println(i);
            }
        }

        for (int i = 52; i <= 100; i++) {
            if (i % 2 == 0) {
                System.out.println(i);
            }
        }
    }
}


}
}
